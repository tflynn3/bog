package idempotency

import (
	"context"
	"time"
)

// Backend defines the transactional storage boundary. Its methods must be safe
// for concurrent calls, including calls from separate coordinators that share
// the same committed state. It may share physical WAL work across keys, but
// admission for an unresolved key must not require recovery of unrelated keys
// unless the storage authority itself is unavailable.
type Backend interface {
	// Commit decides and applies a single keyed ingest transaction. At its
	// commit decision, an existing unexpired record wins and is returned as
	// BackendExisting. Otherwise, the backend may append Batch and install
	// req.RecordAt(now) atomically with the batch. It returns BackendStored
	// only after durability and publication of the whole batch. Use the same
	// time sample for the expiry decision and the new record and acquire it
	// at the commit boundary, after any queuing or preparatory work.
	//
	// Commit must serialize the active-record test and a successful write
	// against other commits and expiry deletion. BackendRolledBack requires
	// proof that this attempt did not publish and can never commit later.
	// Once the outcome is uncertain, leave enough state to resolve it or
	// fence the affected key. Never admit another append for that key based
	// on an index miss while the previous append could still commit.
	//
	// Batch is immutable and may be borrowed until Commit returns. A backend
	// that retains it, including for async recovery, must take ownership of
	// an independent copy.
	Commit(ctx context.Context, req CommitRequest) (BackendResult, error)

	// Resolve asks for the authoritative outcome of the specified attempt
	// without appending anything. BackendStored or BackendExisting must
	// refer to the decision for that attempt. BackendRolledBack requires
	// proof of rollback, including a guarantee against any later commit by
	// that attempt. An absent or expired index entry alone proves neither.
	// Return BackendUnknown when the outcome cannot be established. Recovery
	// of the underlying store must obey the same atomicity before Commit can
	// allow fresh writes for the affected key.
	Resolve(ctx context.Context, key ScopedKey, attempt AttemptID) (BackendResult, error)

	// DeleteExpired deletes records with ExpiresAt <= cutoff. Limit is a
	// bound on both candidates examined and records removed in this call.
	// Recheck expiry atomically with deletion against the current record, or
	// use a conditional delete tied to the selected record's AttemptID.
	// The check must survive concurrent replacement and other cleanup calls.
	// Deleted records never remove their committed batches. Return the
	// actual count, even when some deletions succeeded before an error.
	DeleteExpired(ctx context.Context, cutoff time.Time, limit int) (int, error)
}

// AttemptID identifies one backend commit attempt and distinguishes different
// generations of a scoped key. It is generated by the coordinator, never by
// clients. Persist it with the winning record.
type AttemptID [16]byte

// Record is the committed retry metadata for a key. A backend persists the
// scope, key, record, and durable batch at one commit boundary.
type Record struct {
	AttemptID     AttemptID
	Fingerprint   Fingerprint
	PolicyVersion string
	CommittedAt   time.Time
	ExpiresAt     time.Time
}

// ActiveAt reports whether the record still reserves the key. At exactly
// ExpiresAt the key can be used for a new batch.
func (r Record) ActiveAt(now time.Time) bool {
	return now.Before(r.ExpiresAt)
}

// CommitRequest is constructed by Submit for the backend. It contains only
// the digest of the original request and the prepared durable batch.
type CommitRequest struct {
	Key           ScopedKey
	AttemptID     AttemptID
	Fingerprint   Fingerprint
	PolicyVersion string
	Batch         []byte

	clock  func() time.Time
	window time.Duration
}

// Now samples the coordinator clock in UTC without process-local monotonic
// time. Call it at the authoritative commit decision.
func (r CommitRequest) Now() time.Time {
	return r.clock().UTC()
}

// RecordAt constructs the metadata to install with Batch. Use the same
// timestamp already sampled for the atomic current-record expiry check.
func (r CommitRequest) RecordAt(now time.Time) Record {
	now = now.UTC()
	return Record{
		AttemptID:     r.AttemptID,
		Fingerprint:   r.Fingerprint,
		PolicyVersion: r.PolicyVersion,
		CommittedAt:   now,
		ExpiresAt:     now.Add(r.window),
	}
}

// BackendState describes the authoritative disposition of a commit attempt.
type BackendState uint8

const (
	// BackendUnknown also serves as the zero result. An error on its own never
	// establishes that an attempt rolled back.
	BackendUnknown BackendState = iota
	BackendStored
	BackendExisting
	BackendRolledBack
)

// BackendResult carries a record only for BackendStored and BackendExisting.
// Those successful decisions must have nil errors. BackendRolledBack and
// BackendUnknown may carry a cause as the method's error return.
type BackendResult struct {
	State  BackendState
	Record Record
}
